def build(execute_pdf: bool = True) -> Path:
    if not SOURCE.exists():
        raise FileNotFoundError(
            f"{SOURCE} not found; run examples/_build_report.py first."
        )
    nb = nbf.read(SOURCE, as_version=4)

    md_idx = 0
    untranslated: list[int] = []
    for cell in nb.cells:
        if cell.cell_type != "markdown":
            continue
        if md_idx in RU_MARKDOWN:
            cell.source = RU_MARKDOWN[md_idx]
        elif md_idx != 0:  # cell 0 is the print-CSS block, leave it alone
            stripped = cell.source.strip()
            if stripped and not stripped.startswith("---"):
                untranslated.append(md_idx)
        md_idx += 1

    nbf.write(nb, TARGET_NB)
    print(f"wrote {TARGET_NB.name}  ({md_idx} markdown cells inspected, "
          f"{len(RU_MARKDOWN)} translated, {len(untranslated)} untranslated)")
    if untranslated:
        print(f"  untranslated markdown cells: {untranslated}")

    if not execute_pdf:
        return TARGET_NB

    cmd = [
        sys.executable, "-m", "nbconvert", "--to", "webpdf",
        "--output", TARGET_PDF.stem, str(TARGET_NB),
    ]
    print(f"running: {' '.join(cmd)}")
    subprocess.run(cmd, check=True)
    print(f"wrote {TARGET_PDF.name}")
    return TARGET_PDF


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--no-pdf", action="store_true",
                        help="only write the .ipynb, skip the webpdf conversion")
    args = parser.parse_args()
    build(execute_pdf=not args.no_pdf)
    return 0


if __name__ == "__main__":
    sys.exit(main())
