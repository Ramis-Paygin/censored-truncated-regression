_set(
    5,
    "## 3.1 Теория\n"
    "\n"
    "### Латентная регрессия\n"
    "\n"
    "Обе модели исходят из одной и той же латентной линейной спецификации"
    " с нормальной ошибкой:\n"
    "\n"
    "$$Y^* = X'\\beta + e, \\qquad e \\mid X \\sim \\mathcal{N}(0, \\sigma^2).$$\n"
    "\n"
    "Различие — лишь в правиле, по которому латентная величина $Y^*$"
    " переходит в наблюдаемые данные.\n"
    "\n"
    "### Цензурированная модель\n"
    "\n"
    "Значения за пределами $[L, R]$ **подменяются** ближайшим порогом:\n"
    "\n"
    "$$Y = \\min\\bigl(R,\\; \\max(L,\\; Y^*)\\bigr).$$\n"
    "\n"
    "Обозначая $\\alpha_L = (L - X'\\beta)/\\sigma$ и"
    " $\\alpha_R = (R - X'\\beta)/\\sigma$, в логарифме правдоподобия"
    " складываются точечные массы на порогах и нормальная плотность"
    " на интервале:\n"
    "\n"
    "$$\\ell(\\beta, \\sigma) = \\sum_{Y_i = L} \\log\\Phi(\\alpha_{L,i})\n"
    "+ \\sum_{Y_i = R} \\log\\bigl[1 - \\Phi(\\alpha_{R,i})\\bigr]\n"
    "+ \\sum_{L < Y_i < R} \\Bigl[\\log\\phi(\\alpha_i) - \\log\\sigma\\Bigr],$$\n"
    "\n"
    "где $\\phi$ и $\\Phi$ — плотность и функция распределения стандартного"
    " нормального закона. Классический Tobit соответствует частному"
    " случаю $L = 0$, $R = +\\infty$.\n"
    "\n"
    "### Параметризация Олсена\n"
    "\n"
    "Оптимизация ведётся в переменных $(\\gamma, \\nu) = (\\beta/\\sigma,\\, 1/\\sigma)$."
    " Олсен (1978) показал, что в этих координатах логарифм"
    " правдоподобия **глобально вогнут**, поэтому любой градиентный метод"
    " сходится к единственному максимуму. После сходимости пакет"
    " совершает обратное преобразование к $(\\beta, \\sigma)$ и вычисляет"
    " стандартные ошибки по наблюдаемой информационной матрице.\n"
    "\n"
    "### Усечённая модель\n"
    "\n"
    "В усечённой выборке наблюдений вне $(L, R)$ **нет вовсе**. Плотность"
    " — это нормальная плотность, перенормированная на вероятность"
    " попадания в интервал:\n"
    "\n"
    "$$f(y_i \\mid L < Y_i^* < R) =\n"
    "\\frac{\\sigma^{-1}\\,\\phi\\!\\bigl((y_i - X_i'\\beta)/\\sigma\\bigr)}\n"
    "     {\\Phi(\\alpha_{R,i}) - \\Phi(\\alpha_{L,i})}.$$\n"
    "\n"
    "### Условные средние и предельные эффекты\n"
    "\n"
    "Поддерживаются три условных средних (Hansen, 2022, гл. 27):\n"
    "\n"
    "- **Латентное:** $\\mathbb{E}[Y^* \\mid X] = X'\\beta$\n"
    "- **Цензурированное:** $\\mathbb{E}[Y \\mid X]$ с учётом точечных масс\n"
    "- **Усечённое:** $\\mathbb{E}[Y \\mid X,\\, L < Y < R]$\n"
    "\n"
    "Предельные эффекты доступны в форме **AME** (усреднение по выборке)"
    " и **MEM** (в точке средних регрессоров), обе со стандартными"
    " ошибками по дельта-методу. Цензурированный предельный эффект на"
    " $\\mathbb{E}[Y\\mid X]$ имеет вид"
    " $\\beta_j \\cdot [\\Phi(\\alpha_R) - \\Phi(\\alpha_L)]$ — латентный"
    " наклон, умноженный на вероятность оказаться внутри интервала.\n"
    "\n"
    "### Статистический вывод\n"
    "\n"
    "Каждая подогнанная модель содержит общий LR-тест против модели только"
    " с константой и псевдо-$R^2$ Мак-Фаддена. Сравнить произвольные"
    " вложенные модели позволяет `lr_test`, возвращающий"
    " $LR = 2(\\ell_{\\text{full}} - \\ell_{\\text{restricted}}) \\sim \\chi^2_q$.",
)


